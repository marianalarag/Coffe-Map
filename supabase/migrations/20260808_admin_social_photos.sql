insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'cafe-photos',
  'cafe-photos',
  true,
  8388608,
  array['image/jpeg', 'image/png', 'image/webp', 'image/heic', 'image/heif']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "cafe_photos_storage_read" on storage.objects;
create policy "cafe_photos_storage_read"
on storage.objects for select to authenticated
using (bucket_id = 'cafe-photos');

drop policy if exists "cafe_photos_storage_insert" on storage.objects;
create policy "cafe_photos_storage_insert"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'cafe-photos'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

drop policy if exists "cafe_photos_storage_delete" on storage.objects;
create policy "cafe_photos_storage_delete"
on storage.objects for delete to authenticated
using (
  bucket_id = 'cafe-photos'
  and ((storage.foldername(name))[1] = (select auth.uid())::text or (select private.is_admin()))
);

